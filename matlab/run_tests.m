% A math segédek smoke tesztje; nem helyettesíti a MATLAB-ban végzett teljes QA-t.
clearvars;close all;clc;setup;
s=measurement_stats([9;10;11;10]);
assert(abs(s.mean-10)<1e-12);
assert(abs(s.std-sqrt(2/3))<1e-12);
assert(abs(s.sem-s.std/2)<1e-12);
fprintf('[PASS] átlag/szórás/SEM\n');
[clean,~,removed]=clean_rows_sigma([10*ones(50,1);200],3);
assert(numel(clean)==50 && isequal(removed,51));
fprintf('[PASS] iteratív durvahiba-szűrés\n');
r=fitline_ols((0:4)',(1:2:9)');
assert(abs(r.m-2)<1e-10 && abs(r.b-1)<1e-10);
fprintf('[PASS] lineáris illesztés\n');
fs=1000;t=(0:999)'/fs;
[f,A]=one_sided_fft(3*sin(2*pi*50*t),fs);
[amp,idx]=max(A);
assert(abs(f(idx)-50)<1e-10 && abs(amp-3)<1e-10);
fprintf('[PASS] FFT-frekvencia és amplitúdó\n');
tmp=zeros(100,1);tmp(10)=1;rec=zeros(100,1);rec(30)=1;
delay=echo_delay_local(tmp,rec,1000,340);
assert(abs(delay.lag_samples)==20);
assert(abs(delay.distance_m-3.4)<1e-10);
fprintf('[PASS] időeltolás, oda-vissza távolság\n');
z=sgolay_local((1:51)'.^2,7,2);
assert(abs(z(25)-625)<1e-7);
fprintf('[PASS] polinomsimítás\n');
welch=spectra_welch_local(sin(2*pi*50*t),sin(2*pi*50*t),fs,200);
assert(max(welch.coherence)<1.000001 && max(welch.coherence)>.999);
fprintf('[PASS] PSD/CSD/koherencia\n');
fprintf('Összes alapszintű MATLAB smoke teszt PASS.\\n');
